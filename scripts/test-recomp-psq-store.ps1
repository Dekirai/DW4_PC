param()
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repoRoot = Split-Path -Parent $PSScriptRoot
$dolphinRoot = Join-Path $repoRoot 'work/moderngekko/vendor/dolphin'
$sourceRoot = Join-Path $repoRoot 'tools/recomp_psq_store_check'
$outputRoot = Join-Path $repoRoot 'build/recomp-psq-store-check'
$gxInclude = Join-Path $dolphinRoot 'GXRuntime/include'
$baselineCommit = '55c7b023fa0f4eba1cf3fdbbb25b1c5ec468d5ac'
if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) {
    throw 'The paired-store differential checker requires Windows x64 and MSVC.'
}
[IO.Directory]::CreateDirectory($outputRoot) | Out-Null
$encoding = New-Object System.Text.UTF8Encoding($false)
$inputEvidence = @()
function Read-PinnedSource([string]$RelativePath) {
    $lines = & git -C $dolphinRoot show ($baselineCommit + ':' + $RelativePath)
    if ($LASTEXITCODE -ne 0) { throw "Cannot read pinned source: $RelativePath" }
    return ($lines -join "`n") + "`n"
}
function Extract-Function([string]$Text, [string]$Name) {
    # Preserve positions while removing comments/strings before balancing braces.
    $clean = [regex]::Replace($Text, '(?s)/\*.*?\*/|//[^\r\n]*|"(?:\\.|[^"\\])*"',
        [Text.RegularExpressions.MatchEvaluator]{ param($m) ' ' * $m.Length })
    $pattern = '(?m)^(?:(?:static|inline)\s+)*(?:bool|void|s32|u32|s64)\s+' + [regex]::Escape($Name) + '\s*\('
    $matches = [regex]::Matches($clean, $pattern)
    if ($matches.Count -ne 1) { throw "Expected exactly one definition of $Name." }
    $start = $matches[0].Index
    $brace = $clean.IndexOf('{', $start)
    if ($brace -lt 0 -or $clean.Substring($start, $brace - $start).Contains(';')) {
        throw "Cannot find function body: $Name"
    }
    $depth = 1
    $end = $brace + 1
    while ($end -lt $clean.Length -and $depth -gt 0) {
        if ($clean[$end] -eq '{') { $depth++ }
        if ($clean[$end] -eq '}') { $depth-- }
        $end++
    }
    if ($depth -ne 0) { throw "Unbalanced function: $Name" }
    return $Text.Substring($start, $end - $start)
}
$baselineInclude = Join-Path $outputRoot 'baseline-include'
[IO.Directory]::CreateDirectory((Join-Path $baselineInclude 'core')) | Out-Null
foreach ($relative in @('GXRuntime/include/core/cpu.h', 'GXRuntime/include/core/types.h',
                         'GXRuntime/src/core/cpu.c', 'GXRuntime/src/core/cpu_exception.c')) {
    $pinned = Read-PinnedSource $relative
    $leaf = Split-Path -Leaf $relative
    $pinnedPath = if ($relative.Contains('/include/')) { Join-Path $baselineInclude ('core/' + $leaf) } else { Join-Path $outputRoot ('baseline-' + $leaf) }
    [IO.File]::WriteAllText($pinnedPath, $pinned, $encoding)
    $blob = & git -C $dolphinRoot rev-parse ($baselineCommit + ':' + $relative)
    if ($LASTEXITCODE -ne 0) { throw "Cannot resolve pinned blob: $relative" }
    $inputEvidence += [ordered]@{ relative_path = $relative; baseline_blob = [string]$blob;
        baseline_sha256 = (Get-FileHash -LiteralPath $pinnedPath -Algorithm SHA256).Hash;
        current_sha256 = (Get-FileHash -LiteralPath (Join-Path $dolphinRoot $relative) -Algorithm SHA256).Hash }
}
$baselineHeader = [IO.File]::ReadAllText((Join-Path $baselineInclude 'core/cpu.h'))
$currentHeader = [IO.File]::ReadAllText((Join-Path $gxInclude 'core/cpu.h'))
$structPattern = '(?s)struct CPUState \{.*?\n\};'
$baselineStruct = [regex]::Match($baselineHeader, $structPattern).Value.Replace("`r", '')
$currentStruct = [regex]::Match($currentHeader, $structPattern).Value.Replace("`r", '')
if (-not $baselineStruct -or $baselineStruct -ne $currentStruct) {
    throw 'CPUState layout differs from the pinned baseline; review the harness ABI before proceeding.'
}
foreach ($variant in @('baseline', 'current')) {
    $isBaseline = $variant -eq 'baseline'
    $cpuText = if ($isBaseline) { [IO.File]::ReadAllText((Join-Path $outputRoot 'baseline-cpu.c')) } else { [IO.File]::ReadAllText((Join-Path $dolphinRoot 'GXRuntime/src/core/cpu.c')) }
    $exceptionText = if ($isBaseline) { [IO.File]::ReadAllText((Join-Path $outputRoot 'baseline-cpu_exception.c')) } else { [IO.File]::ReadAllText((Join-Path $dolphinRoot 'GXRuntime/src/core/cpu_exception.c')) }
    $parts = @('// SPDX-License-Identifier: GPL-3.0-or-later', '// Actual GXRuntime functions; generated by the differential checker.')
    foreach ($symbol in @('ppc_psq_store', 'ppc_program_exception', 'ppc_take_exception', 'g_mem_write_journal', 'g_mem_write_journal_user')) {
        $parts += '#define ' + $symbol + ' ' + $variant + '_' + $symbol
    }
    $parts += @('#include "core/cpu.h"', '#include <math.h>',
        'PPCMemWriteJournal g_mem_write_journal = NULL;', 'void* g_mem_write_journal_user = NULL;')
    $names = @('gqr_scale', 'psq_type_size')
    if ($isBaseline) { $names += 'psq_quantize_int' }
    $names += @('psq_store_value', 'psq_check_enabled', 'ppc_psq_store')
    foreach ($name in $names) { $parts += Extract-Function $cpuText $name }
    foreach ($name in @('exception_vector_address', 'exception_msr', 'ppc_take_exception', 'ppc_program_exception')) {
        $parts += Extract-Function $exceptionText $name
    }
    $parts += "void ${variant}_set_journal(PPCMemWriteJournal fn, void* user) { g_mem_write_journal = fn; g_mem_write_journal_user = user; }"
    if (-not $isBaseline) {
        $parts += '__declspec(noinline) bool current_inline_store(CPUState* cpu, u8 frS, u32 ea, bool w, u8 gqr, bool indexed, u32 cia) { return ppc_psq_store_inline(cpu, frS, ea, w, gqr, indexed, cia); }'
    }
    [IO.File]::WriteAllText((Join-Path $outputRoot ($variant + '.c')), ($parts -join "`n`n") + "`n", $encoding)
}
if (-not (Get-Command cl.exe -CommandType Application -ErrorAction SilentlyContinue)) {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
    if (-not (Test-Path -LiteralPath $vswhere)) { throw 'Visual Studio with the C++ workload is required.' }
    $installation = [string](& $vswhere -latest -prerelease -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath)
    if ($LASTEXITCODE -ne 0 -or -not $installation.Trim()) { throw 'Could not locate the MSVC x64 toolchain.' }
    $environmentScript = Join-Path $outputRoot 'compiler-env.cmd'
    $vcvars = Join-Path $installation.Trim() 'VC/Auxiliary/Build/vcvars64.bat'
    @('@echo off', ('call "' + $vcvars + '" >nul'), 'if errorlevel 1 exit /b %errorlevel%', 'set') |
        Set-Content -LiteralPath $environmentScript -Encoding ascii
    $compilerEnvironment = & $env:ComSpec /d /c $environmentScript
    if ($LASTEXITCODE -ne 0) { throw 'The MSVC x64 environment could not be initialized.' }
    foreach ($entry in $compilerEnvironment) {
        if ($entry -match '^([^=]+)=(.*)$') { [Environment]::SetEnvironmentVariable($Matches[1], $Matches[2], 'Process') }
    }
}
$compiler = (Get-Command cl.exe -CommandType Application -ErrorAction Stop | Select-Object -First 1).Source
$logPath = Join-Path $outputRoot 'build.log'
[IO.File]::WriteAllText($logPath, '')
function Invoke-CheckerCommand([string]$Executable, [string[]]$Arguments) {
    $savedPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        & $Executable @Arguments 2>&1 | Tee-Object -FilePath $logPath -Append -ErrorAction Stop
        $nativeExit = $LASTEXITCODE
    } finally { $ErrorActionPreference = $savedPreference }
    if ($nativeExit -ne 0) { throw "Paired-store checker command failed ($nativeExit): $Executable. See $logPath" }
}
$objects = @()
foreach ($name in @('baseline', 'current', 'timing', 'main')) {
    $object = Join-Path $outputRoot ($name + '.obj')
    $include = if ($name -eq 'baseline') { $baselineInclude } else { $gxInclude }
    $arguments = @('/nologo', '/c', '/O2', '/fp:strict', '/W4', '/WX', '/MD', '/utf-8', "/I$include")
    if ($name -eq 'main') { $arguments += @('/std:c++20', '/EHsc', (Join-Path $sourceRoot 'main.cpp')) }
    elseif ($name -eq 'timing') { $arguments += @('/TC', '/std:c11', (Join-Path $sourceRoot 'timing.c')) }
    else { $arguments += @('/TC', '/std:c11', (Join-Path $outputRoot ($name + '.c'))) }
    Invoke-CheckerCommand $compiler ($arguments + @("/Fo$object", '/FAs', ("/Fa" + (Join-Path $outputRoot ($name + '.asm')))))
    $objects += $object
}
$executable = Join-Path $outputRoot 'recomp-psq-store-check.exe'
Invoke-CheckerCommand $compiler (@('/nologo') + $objects + @("/Fe$executable", '/link', '/MACHINE:X64'))
$reportPath = Join-Path $outputRoot 'latest.json'
Invoke-CheckerCommand $executable @($reportPath)
$report = Get-Content -LiteralPath $reportPath -Raw | ConvertFrom-Json
if (-not $report.passed -or $report.original_mxcsr -ne $report.restored_mxcsr) { throw 'Paired-store equivalence or MXCSR restoration failed.' }
foreach ($evidenceEntry in $inputEvidence) {
    if ($evidenceEntry.current_sha256 -ne (Get-FileHash -LiteralPath (Join-Path $dolphinRoot $evidenceEntry.relative_path) -Algorithm SHA256).Hash) {
        throw "Source changed while checking: $($evidenceEntry.relative_path)"
    }
}
$record = [ordered]@{
    checked_at_utc = [DateTime]::UtcNow.ToString('o'); baseline_commit = $baselineCommit; inputs = $inputEvidence
    baseline_extracted_sha256 = (Get-FileHash -LiteralPath (Join-Path $outputRoot 'baseline.c') -Algorithm SHA256).Hash
    current_extracted_sha256 = (Get-FileHash -LiteralPath (Join-Path $outputRoot 'current.c') -Algorithm SHA256).Hash
    checker_source_sha256 = (Get-FileHash -LiteralPath (Join-Path $sourceRoot 'main.cpp') -Algorithm SHA256).Hash
    timing_source_sha256 = (Get-FileHash -LiteralPath (Join-Path $sourceRoot 'timing.c') -Algorithm SHA256).Hash
    wrapper_sha256 = (Get-FileHash -LiteralPath $PSCommandPath -Algorithm SHA256).Hash
    checker_sha256 = (Get-FileHash -LiteralPath $executable -Algorithm SHA256).Hash
    compiler = $compiler; compiler_version = [Diagnostics.FileVersionInfo]::GetVersionInfo($compiler).FileVersion
    compile_options = '/O2 /fp:strict /W4 /WX /MD; helpers /TC /std:c11; harness /std:c++20; no LTCG'
    report = $reportPath; game_code_executed = $false; synthetic_timing_performed = $report.synthetic_timing.performed
}
$record | ConvertTo-Json -Depth 7 | Set-Content -LiteralPath (Join-Path $outputRoot 'invocation.json') -Encoding utf8
Write-Host "Paired-store equivalence evidence: $reportPath"
